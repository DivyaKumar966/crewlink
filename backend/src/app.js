import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import authRoutes from './routes/authRoutes.js';
import userRoutes from './routes/userRoutes.js';
import projectRoutes from './routes/projectRoutes.js';
import workspaceRoutes from './routes/workspaceRoutes.js';
import adminRoutes from './routes/adminRoutes.js';
import githubRoutes from './routes/githubRoutes.js';
import notificationRoutes from './routes/notificationRoutes.js';

const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_URL || 'http://localhost:5173'}));
app.use(express.json({ verify: (req, res, buffer) => { req.rawBody = Buffer.from(buffer); } }));
app.get('/api/health',(req,res)=>res.json({status:'ok',app:'CREWLINK'}));
app.use('/api/auth',authRoutes);
app.use('/api/users',userRoutes);
app.use('/api/projects',projectRoutes);
app.use('/api/workspace',workspaceRoutes);
app.use('/api/admin',adminRoutes);
app.use('/api/github',githubRoutes);
app.use('/api/notifications',notificationRoutes);
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({message:'Something went wrong'});});
export default app;
